export function formatPaperAsMarkdown(project: ResearchProject): string {
  const { paper, topicInput } = project;

  return `# ${paper.title}

> **Field:** ${topicInput.field}  
> **Target Level:** ${topicInput.academicLevel}  
> **Methodology:** ${topicInput.methodologyPreference}  
> *Generated by AI Academic Research Paper Agent*

---

## Abstract
${paper.abstract}

**Keywords:** *${paper.keywords.join(', ')}*

---

## 1. Introduction
${paper.introduction}

## 2. Problem Statement
${paper.problemStatement}

## 3. Literature Review
${paper.literatureReview}

## 4. Research Objectives
${paper.researchObjectives}

## 5. Methodology
${paper.methodology}

## 6. Results and Discussion
> ⚠️ **Empirical Disclosure & Disclaimer:**  
> ${paper.resultsAndDiscussion.disclaimer}

${paper.resultsAndDiscussion.content}

${
  paper.resultsAndDiscussion.keyMetrics && paper.resultsAndDiscussion.keyMetrics.length > 0
    ? `\n### Key Experimental Benchmarks\n` +
      `| Metric | Value | Scholarly Context |\n| :--- | :--- | :--- |\n` +
      paper.resultsAndDiscussion.keyMetrics
        .map((m) => `| **${m.label}** | \`${m.value}\` | ${m.explanation} |`)
        .join('\n')
    : ''
}

## 7. Conclusion
${paper.conclusion}

## 8. Future Scope
${paper.futureScope}

## 9. References
${paper.references
  .map(
    (ref, i) =>
      `${i + 1}. ${ref.citationApa} ${
        ref.doiOrUrl ? `[Link](${ref.doiOrUrl})` : ''
      } ${ref.isVerified ? '*(Verified Grounded Source)*' : '*(Suggested Literature Direction)*'}`
  )
  .join('\n\n')}
`;
}

export function formatAllCitations(project: ResearchProject, format: CitationFormat): string {
  return project.paper.references
    .map((ref, idx) => {
      let text = '';
      if (format === 'APA') text = ref.citationApa;
      else if (format === 'IEEE') text = ref.citationIeee;
      else if (format === 'MLA') text = ref.citationMla;
      if (ref.doiOrUrl) {
        text += ` [${ref.doiOrUrl}]`;
      }
      return `${idx + 1}. ${text}`;
    })
    .join('\n\n');
}

export function formatBibtexAll(project: ResearchProject): string {
  return project.paper.references.map((r) => r.bibtex).join('\n\n');
}

export function downloadBlob(content: string, filename: string, mimeType: string) {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
